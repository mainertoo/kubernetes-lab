#!/usr/bin/env python3
"""Hand the legacy ClusterPolicy's generated VolSync objects to the CEL GeneratingPolicy.

Kyverno CEL migration (docs/plans/kyverno-cel-migration.md), run once right
after the Kyverno 1.20 cutover:
  - the legacy ClusterPolicy volsync-pvc-backup-restore-kopia is gone (inert
    on 1.20, so its deletion removed nothing),
  - the GeneratingPolicy volsync-pvc-backup-objects is in place,
  - features.protectGenerationLabels.enabled is false, so generate.kyverno.io
    labels can be edited.

On 1.20 the GeneratingPolicy ignores objects that carry another policy's
generate labels. This script relabels every Secret / ReplicationSource /
ReplicationDestination generated by the legacy policy to the
GeneratingPolicy's labels, then annotates each trigger PVC once so the policy
re-evaluates it and adopts the objects in place (same UID: no RD is recreated,
so no restore-once restore re-runs).

Usage:
  adopt-legacy-generated.py --context staging            # dry run (default)
  adopt-legacy-generated.py --context staging --apply
A UID snapshot is written next to --snapshot (default ./adopt-snapshot-<ctx>.json).
"""
import argparse
import json
import subprocess
import sys
import time

LEGACY = "volsync-pvc-backup-restore-kopia"
GPOL = "volsync-pvc-backup-objects"
KINDS = ["secrets", "replicationsources.volsync.backube", "replicationdestinations.volsync.backube"]
L = "generate.kyverno.io/"
TOUCH = "kyverno-cel-migration/adopted-at"


def kubectl(ctx, *args, check=True):
    cmd = ["kubectl", "--context", ctx, "--request-timeout=60s", *args]
    for attempt in range(3):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode == 0 or not check:
            return r
        if "Unable to connect" not in r.stderr and "timeout" not in r.stderr.lower():
            break
        time.sleep(5 * (attempt + 1))
    sys.exit(f"kubectl {' '.join(args)} failed: {r.stderr.strip()[:300]}")


def get_json(ctx, *args):
    return json.loads(kubectl(ctx, *args, "-o", "json").stdout)


def preflight(ctx):
    problems = []
    hooks = get_json(ctx, "get", "validatingwebhookconfigurations")
    names = [w["name"] for c in hooks["items"] for w in c.get("webhooks", [])]
    if any(n.startswith("protect-generation-labels") for n in names):
        problems.append("protect-generation-labels webhook is active "
                        "(set features.protectGenerationLabels.enabled=false first)")
    if kubectl(ctx, "get", "generatingpolicies.policies.kyverno.io", GPOL, check=False).returncode != 0:
        problems.append(f"GeneratingPolicy {GPOL} not found")
    if kubectl(ctx, "get", "clusterpolicies.kyverno.io", LEGACY, check=False).returncode == 0:
        problems.append(f"legacy ClusterPolicy {LEGACY} still exists (remove it on 1.20 first)")
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--context", required=True)
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--snapshot")
    a = ap.parse_args()
    snap_path = a.snapshot or f"adopt-snapshot-{a.context}.json"

    problems = preflight(a.context)
    for p in problems:
        print("PRE-FLIGHT:", p)
    if problems and a.apply:
        sys.exit("pre-flight failed; nothing changed")

    objs = []
    for kind in KINDS:
        objs += get_json(a.context, "get", kind, "-A", "-l", f"{L}policy-name={LEGACY}")["items"]
    pvcs = {p["metadata"]["uid"]: p for p in get_json(a.context, "get", "pvc", "-A")["items"]}

    plan, orphans = [], []
    for o in objs:
        m = o["metadata"]
        pvc = pvcs.get(m["labels"].get(f"{L}trigger-uid", ""))
        if pvc is None or pvc["metadata"]["namespace"] != m["namespace"]:
            orphans.append(f"{o['kind']}/{m['namespace']}/{m['name']}")
            continue
        plan.append({"kind": o["kind"], "apiVersion": o["apiVersion"], "ns": m["namespace"],
                     "name": m["name"], "uid": m["uid"], "pvc": pvc["metadata"]["name"]})

    pvcs_to_touch = sorted({(p["ns"], p["pvc"]) for p in plan})
    print(f"legacy-labelled objects: {len(objs)}  adoptable: {len(plan)}  "
          f"trigger PVCs: {len(pvcs_to_touch)}  orphans (no matching PVC, skipped): {len(orphans)}")
    for o in orphans:
        print("  ORPHAN", o)
    if not a.apply:
        for p in plan[:6]:
            print(f"  would relabel {p['kind']}/{p['ns']}/{p['name']} -> trigger-name={p['pvc']}")
        print("dry run: nothing changed (use --apply)")
        return

    json.dump(plan, open(snap_path, "w"), indent=1)
    print("UID snapshot:", snap_path)

    kind_arg = {"Secret": "secret", "ReplicationSource": "replicationsources.volsync.backube",
                "ReplicationDestination": "replicationdestinations.volsync.backube"}
    for p in plan:
        kubectl(a.context, "-n", p["ns"], "label", kind_arg[p["kind"]], p["name"], "--overwrite",
                f"{L}policy-name={GPOL}", f"{L}trigger-name={p['pvc']}",
                f"{L}rule-name-", f"{L}policy-namespace-")
    print(f"relabelled {len(plan)} objects")

    stamp = str(int(time.time()))
    for ns, pvc in pvcs_to_touch:
        kubectl(a.context, "-n", ns, "annotate", "pvc", pvc, "--overwrite", f"{TOUCH}={stamp}")
    print(f"annotated {len(pvcs_to_touch)} PVCs")

    time.sleep(20)
    bad = 0
    for p in plan:
        cur = get_json(a.context, "-n", p["ns"], "get", kind_arg[p["kind"]], p["name"])
        lab = cur["metadata"].get("labels", {})
        ok = (cur["metadata"]["uid"] == p["uid"] and lab.get(f"{L}policy-name") == GPOL
              and lab.get(f"{L}trigger-name") == p["pvc"] and f"{L}rule-name" not in lab)
        if not ok:
            bad += 1
            print("  NOT OK", p["kind"], p["ns"], p["name"],
                  "uid-same" if cur["metadata"]["uid"] == p["uid"] else "UID-CHANGED")
    print(f"verified: {len(plan) - bad}/{len(plan)} objects relabelled with unchanged UIDs")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
